/**
 * Searches service providers by name, alias, country, city, or email.
 */
export function searchServiceProviders(query: string): PredefinedServiceProvider[] {
  const q = (query || '').trim().toLowerCase();
  if (!q) return PREDEFINED_SERVICE_PROVIDERS;

  return PREDEFINED_SERVICE_PROVIDERS.filter((sp) => {
    if (sp.name.toLowerCase().includes(q)) return true;
    if (sp.city.toLowerCase().includes(q)) return true;
    if (sp.country.toLowerCase().includes(q)) return true;
    if (sp.countryCode.toLowerCase().includes(q)) return true;
    if (sp.generalEmail.toLowerCase().includes(q)) return true;
    if (sp.websiteUrl.toLowerCase().includes(q)) return true;
    if (sp.aliasNames && sp.aliasNames.some((a) => a.toLowerCase().includes(q))) return true;
    if (sp.contactPerson && sp.contactPerson.toLowerCase().includes(q)) return true;
    return false;
  });
}

/**
 * Finds a service provider by ID
 */
export function getServiceProviderById(id: string): PredefinedServiceProvider | undefined {
  return PREDEFINED_SERVICE_PROVIDERS.find((sp) => sp.id === id);
}

/**
 * Finds a service provider by name match (exact or close match)
 */
export function findServiceProviderByName(name: string): PredefinedServiceProvider | undefined {
  const norm = (name || '').trim().toLowerCase();
  if (!norm) return undefined;
  return PREDEFINED_SERVICE_PROVIDERS.find(
    (sp) =>
      sp.name.toLowerCase() === norm ||
      sp.aliasNames?.some((a) => a.toLowerCase() === norm)
  );
}
